type Legal = Partial<Record<LegalKey, string>>;

function V({ legal, k }: { legal: Legal; k: LegalKey }) {
  const v = legal[k]?.trim();
  return v ? <>{v}</> : <mark className="todo">【要記入：{LEGAL_FIELDS[k].replace(/（.*）$/, "")}】</mark>;
}

function Contact({ legal }: { legal: Legal }) {
  const c = legal.contact?.trim() ?? "";
  if (/^https?:\/\//.test(c)) return <a href={c}>{c}</a>;
  if (c.includes("@")) return <a href={`mailto:${c}`}>{c}</a>;
  return <V legal={legal} k="contact" />;
}

export function missingLegal(legal: Legal, keys: LegalKey[]): string[] {
  return keys.filter((k) => !legal[k]?.trim()).map((k) => LEGAL_FIELDS[k].replace(/（.*）$/, ""));
}

function Toc({ items }: { items: [string, string][] }) {
  return (
    <nav className="toc card" aria-label="目次">
      <ol>{items.map(([id, label]) => <li key={id}><a href={`#${id}`}>{label}</a></li>)}</ol>
    </nav>
  );
}

